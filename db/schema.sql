-- 1. Return one arbitrary organization whose employeesCount is minimal.
CREATE OR REPLACE FUNCTION lab1_organization_with_min_employees()
RETURNS SETOF organizations
LANGUAGE sql
STABLE
AS $$
    SELECT o.*
    FROM organizations o
    ORDER BY o.employees_count ASC, o.id ASC
    LIMIT 1;
$$;

-- 2. Return organizations whose name starts with the supplied substring.
CREATE OR REPLACE FUNCTION lab1_organizations_name_starts_with(p_prefix TEXT)
RETURNS SETOF organizations
LANGUAGE sql
STABLE
AS $$
    SELECT o.*
    FROM organizations o
    WHERE o.name LIKE COALESCE(p_prefix, '') || '%'
    ORDER BY o.id;
$$;

-- 3. Enum declaration order is used for comparison:
-- COMMERCIAL < GOVERNMENT < PRIVATE_LIMITED_COMPANY.
CREATE OR REPLACE FUNCTION lab1_organizations_type_greater_than(p_type TEXT)
RETURNS SETOF organizations
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_rank INTEGER;
BEGIN
    v_rank := CASE p_type
        WHEN 'COMMERCIAL' THEN 1
        WHEN 'GOVERNMENT' THEN 2
        WHEN 'PRIVATE_LIMITED_COMPANY' THEN 3
        ELSE NULL
    END;

    IF v_rank IS NULL THEN
        RAISE EXCEPTION 'Unknown OrganizationType: %', p_type;
    END IF;

    RETURN QUERY
    SELECT o.*
    FROM organizations o
    WHERE (CASE o.type
        WHEN 'COMMERCIAL' THEN 1
        WHEN 'GOVERNMENT' THEN 2
        WHEN 'PRIVATE_LIMITED_COMPANY' THEN 3
        ELSE 0
    END) > v_rank
    ORDER BY o.id;
END;
$$;

-- 4. Merge two organizations by creating a NEW organization.
-- The source organizations remain unchanged.
-- Required by the assignment: employees are summed, name/address are supplied by the user.
-- For the remaining mandatory fields we use deterministic merger semantics:
--   coordinates = first organization;
--   annual turnover = sum;
--   rating = max;
--   type = greater of the two enum values;
--   postalAddress = NULL.
-- Address can be either an existing Address id or a new Address. A new Address can use
-- either an existing Location id or a newly supplied Location.
CREATE OR REPLACE FUNCTION lab1_merge_organizations(
    p_first_id INTEGER,
    p_second_id INTEGER,
    p_new_name TEXT,
    p_existing_address_id INTEGER,
    p_zip_code TEXT,
    p_existing_town_id INTEGER,
    p_town_x DOUBLE PRECISION,
    p_town_y DOUBLE PRECISION,
    p_town_z INTEGER,
    p_town_name TEXT
)
RETURNS INTEGER
LANGUAGE plpgsql
VOLATILE
AS $$
DECLARE
    v_first organizations%ROWTYPE;
    v_second organizations%ROWTYPE;
    v_address_id INTEGER;
    v_town_id INTEGER;
    v_new_id INTEGER;
    v_first_rank INTEGER;
    v_second_rank INTEGER;
    v_result_type TEXT;
BEGIN
    IF p_first_id IS NULL OR p_second_id IS NULL THEN
        RAISE EXCEPTION 'Both source organization ids are required';
    END IF;
    IF p_first_id = p_second_id THEN
        RAISE EXCEPTION 'Source organizations must be different';
    END IF;
    IF p_new_name IS NULL OR btrim(p_new_name) = '' THEN
        RAISE EXCEPTION 'New organization name must not be blank';
    END IF;

    SELECT * INTO v_first FROM organizations WHERE id = p_first_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Organization with id=% not found', p_first_id;
    END IF;

    SELECT * INTO v_second FROM organizations WHERE id = p_second_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Organization with id=% not found', p_second_id;
    END IF;

    IF p_existing_address_id IS NOT NULL THEN
        SELECT id INTO v_address_id FROM addresses WHERE id = p_existing_address_id;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Address with id=% not found', p_existing_address_id;
        END IF;
    ELSE
        IF p_zip_code IS NULL THEN
            RAISE EXCEPTION 'zipCode is required for a new address';
        END IF;

        IF p_existing_town_id IS NOT NULL THEN
            SELECT id INTO v_town_id FROM locations WHERE id = p_existing_town_id;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Location with id=% not found', p_existing_town_id;
            END IF;
        ELSE
            IF p_town_x IS NULL OR p_town_y IS NULL OR p_town_z IS NULL OR p_town_name IS NULL OR btrim(p_town_name) = '' THEN
                RAISE EXCEPTION 'All Location fields are required for a new town';
            END IF;

            INSERT INTO locations(x, y, z, name)
            VALUES (p_town_x, p_town_y, p_town_z, btrim(p_town_name))
            RETURNING id INTO v_town_id;
        END IF;

        INSERT INTO addresses(zip_code, town_id)
        VALUES (p_zip_code, v_town_id)
        RETURNING id INTO v_address_id;
    END IF;

    v_first_rank := CASE v_first.type
        WHEN 'COMMERCIAL' THEN 1 WHEN 'GOVERNMENT' THEN 2 WHEN 'PRIVATE_LIMITED_COMPANY' THEN 3 ELSE 0 END;
    v_second_rank := CASE v_second.type
        WHEN 'COMMERCIAL' THEN 1 WHEN 'GOVERNMENT' THEN 2 WHEN 'PRIVATE_LIMITED_COMPANY' THEN 3 ELSE 0 END;
    v_result_type := CASE GREATEST(v_first_rank, v_second_rank)
        WHEN 1 THEN 'COMMERCIAL'
        WHEN 2 THEN 'GOVERNMENT'
        ELSE 'PRIVATE_LIMITED_COMPANY'
    END;

    INSERT INTO organizations(
        name, coordinates_id, creation_date, official_address_id,
        annual_turnover, employees_count, rating, type, postal_address_id
    ) VALUES (
        btrim(p_new_name),
        v_first.coordinates_id,
        CURRENT_TIMESTAMP,
        v_address_id,
        v_first.annual_turnover + v_second.annual_turnover,
        v_first.employees_count + v_second.employees_count,
        GREATEST(v_first.rating, v_second.rating),
        v_result_type,
        NULL
    ) RETURNING id INTO v_new_id;

    RETURN v_new_id;
END;
$$;

-- 5. Add one employee to the organization with the specified id.
CREATE OR REPLACE FUNCTION lab1_add_employee(p_organization_id INTEGER)
RETURNS INTEGER
LANGUAGE plpgsql
VOLATILE
AS $$
DECLARE
    v_id INTEGER;
BEGIN
    UPDATE organizations
    SET employees_count = employees_count + 1
    WHERE id = p_organization_id
    RETURNING id INTO v_id;

    IF v_id IS NULL THEN
        RAISE EXCEPTION 'Organization with id=% not found', p_organization_id;
    END IF;

    RETURN v_id;
END;
$$;
