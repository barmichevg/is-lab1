-- Lab 1 database schema and required PostgreSQL functions.
-- Safe to run repeatedly. Existing data is preserved.

CREATE TABLE IF NOT EXISTS coordinates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    x INTEGER NOT NULL,
    y INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    z INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS addresses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zip_code VARCHAR(255) NOT NULL,
    town_id INTEGER NOT NULL REFERENCES locations(id)
);

CREATE TABLE IF NOT EXISTS organizations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    coordinates_id INTEGER NOT NULL REFERENCES coordinates(id),
    creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    official_address_id INTEGER NOT NULL REFERENCES addresses(id),
    annual_turnover REAL NOT NULL,
    employees_count BIGINT NOT NULL,
    rating INTEGER NOT NULL,
    type VARCHAR(64) NOT NULL,
    postal_address_id INTEGER NULL REFERENCES addresses(id)
);

